function formatarTextoEmSpans(texto) {
    let indice = 0;

    return texto.replace(/(<[^>]*>)|(\S+)/g, (match, tag, palavra) => {
        if (tag) {
            return tag;
        }

        return `<span class="palavra" id="palavra-${indice++}">${palavra}</span>`;
    });
}

formatarTextoEmSpans.contador = 0;

